/**
 * @module        终端输出的结构——命令产出的不是一段文字，而是一组有类型的结果
 * @problem       真终端里，程序的输出是一串字符，界面只负责把字符画在屏幕上。
 *                这个项目不能这么做：这里的 ls 每一项都要能点、目录树要能折叠、代码块要能高亮。
 *                如果命令直接吐出拼好的字符串，界面就只剩一个选择——把它当纯文本显示；
 *                想让某一项可点，就得反过来解析那段文字（“第几列是名字？”），
 *                那是把已经有的信息先扔掉再猜回来，既脆又蠢。
 * @design        命令返回一组“块”，每一块自带类型：现在有三种，文字块、列表块（条目可以带一条点击命令）、树块（tree 用）。
 *                界面看类型决定怎么画。
 *                这些类型里没有任何颜色、字号、间距——那是界面的事；这里只说“这是什么”，不说“长什么样”。
 *                另一种做法是让命令直接返回 React 组件，那样最省事，但命令引擎会立刻和网页绑死，
 *                再也没法脱离浏览器测试，本项目明令禁止。
 * @courses       UC Berkeley CS61A（数据抽象：先定表示，再定操作）；Stanford CS143 与 UCB CS164（中间表示：
 *                前一段产出结构、后一段消费结构）；MIT Missing Semester（Unix 管道为什么只能传文本，
 *                以及这带来的限制）；软件工程类课程（分层与接口设计）
 * @exercises     https://cs61a.org/                                  —— 抽象屏障：谁该知道数据长什么样
 *                https://web.stanford.edu/class/cs143/               —— 编译器各阶段之间传的是结构，不是文本
 *                https://missing.csail.mit.edu/2020/data-wrangling/  —— 体会一下“只能传文本”的代价
 * @prereq        知道一个对象可以有一个叫 type 的字段，用来表明它是哪一种东西。
 * @unclear       进度条、表格、代码块这些块还没有，等真有命令要产出它们时再加；
 *                提前定义没人产出的类型，只会得到一堆没被验证过的猜测。
 *                status 的整体统计现在是用文字拼出来的，严格说该有一种“进度条块”，还没做。
 *
 * @letter
 * 这个文件很短，但如果只能挑一个文件来说明“这个终端和别的网页终端有啥不一样”，我就挑它。
 *
 * 先回想一下真终端。你敲 ls，屏幕上出来一列文件名。这些名字对终端来说只是一串字符，它并不知道“这一段是个文件名”。
 * 所以你没法点它们，也没法让某一行变成一个进度条。
 * 管道也是一个道理：前一个命令交给后一个命令的，只有一串字。后一个命令得自己把这串字重新切开，猜出哪儿是哪儿。
 * 这是 Unix 特别成功的一个设计，因为它让随便两个程序都能接起来。
 * 代价是每个程序都得自己写一遍“怎么切”，而且经常切错。文件名里带个空格，好多脚本就翻车了，这是出了名的老坑。
 *
 * 这个终端不接真的 shell，输出也不用在不同程序之间传，所以这个代价可以不付。
 * 命令直接交出带结构的东西：“这是一段字”“这是一个列表，有三项，每项有名字、说明、点了干啥”“这是一棵树”。
 * 界面拿到以后，字就画成字，列表就画成一行行能点的，树就画成能折叠的。
 * 信息从头到尾没被压扁成字符串，所以也没人需要把它再猜回来。
 *
 * 你可能注意到了，这些类型里没有一个颜色、一个字号。这是故意的。
 * “这是一条错误信息”，这是命令知道的事实；“错误信息用红色显示”，这是界面的决定。
 * 命令只说事实，界面来定长相。哪天想把报错换个颜色，只改界面就行。
 * 要是命令里写死了红色，你就得挨个去改每一条命令，而且命令从此离不开屏幕，没法在测试里跑了。
 * 这种“说事实、不说长相”的分工，你以后读任何分层设计的代码都会反复看到，HTML 和 CSS 的分工也是这个意思。
 *
 * 还有一个小细节我挺喜欢：OutputBlock 是几种块的“联合类型”，界面那边处理的时候会挨个类型去处理。
 * 将来要是加一种新块，界面忘了处理它，TypeScript 会直接报错，你根本没机会忘。
 * 能让编译器替你记住的事，就别靠自己的记性。
 */

/** 一段文字的语气。界面据此决定怎么显示，命令本身不关心显示成什么样。 */
export type OutputTone =
  /** 普通输出。 */
  | "normal"
  /** 出错了，比如 command not found。 */
  | "error"
  /** 次要说明，比如提示、脚注。 */
  | "muted";

/** 一段文字。 */
export type TextBlock = { type: "text"; text: string; tone: OutputTone };

/** 列表里的一项：一个标签，外加一句可选的说明。 */
export type ListItem = {
  label: string;
  description?: string;
  /** 有这个字段时，界面把条目画成按钮；点击就像亲手输入这条命令。 */
  command?: string;
  /** 这一项是目录还是文件。ls 会填，界面据此给目录换个颜色；不填就当普通条目。 */
  kind?: "directory" | "file";
};

/** 一组并列的条目，比如 help 列出的命令、将来 ls 列出的课程。 */
export type ListBlock = { type: "list"; items: ListItem[] };

/** 命令能产出的所有块。将来新增类型时，在这里加一种，界面层会因为少处理一种而报错——这是好事。 */
export type TreeItem = {label:string; command:string; children?:TreeItem[]};
export type TreeBlock = {type:'tree'; root:TreeItem};
export type OutputBlock = TextBlock | ListBlock | TreeBlock;

/** 造一段文字。写成函数只是图个顺手，省得每次都写 type: "text"。 */
export function text(content: string, tone: OutputTone = "normal"): TextBlock {
  return { type: "text", text: content, tone };
}

/** 造一个列表。 */
export function list(items: ListItem[]): ListBlock {
  return { type: "list", items };
}
