/**
 * @module        没保存的草稿暂存区——切到别的标签再切回来，写了一半的字还在
 * @problem       标签页一切换，原来那一页的编辑器就被卸载了，它手里没保存的文字跟着消失。
 *                VS Code 里切标签从不丢字，这里也不该丢。
 * @design        一张放在内存里的表：条目编号 → 草稿文字。编辑器每次改动都写进来，打开时先看这里有没有草稿。
 *                只放内存、不进浏览器存储：草稿本来就是“还没决定要不要留”的东西，刷新网页前标签栏会提醒你保存。
 * @courses       UC Berkeley CS61A（状态放在哪一层）；Stanford CS147（防止数据丢失的设计）
 * @exercises     https://cs61a.org/ —— CS61A 里关于状态放在哪一层的 lab
 * @prereq        知道一个模块里的变量在整个页面存活期间只有一份，所有组件共用。
 * @unclear       刷新或关掉网页，草稿就没了；浏览器会先弹“确定离开吗”，但不会替你保存。
 *                VS Code 默认有“热退出”，关窗口时保留未保存的内容；这里没做，要做得先设计好“多份版本怎么挑”的界面。
 *
 * @letter
 * 你在心得编辑器里写了一半，切到别的标签再切回来，写了一半的字还在。靠的就是这张放在内存里的小表：条目编号对应草稿文字。
 *
 * 这是全站唯一一处“故意只放在内存里”的读者数据，跟终端的命令历史是一类：会话状态，刷新就没。
 * 刷新或者关网页之前，浏览器会先弹一句“确定离开吗”，提醒你还有没保存的东西。
 *
 * 为什么不干脆也存进浏览器，刷新了也不丢？
 * 因为一旦存了，你面前就会有三份版本：已经保存的、正在编辑的、上次没关掉留下来的草稿。你得去想哪份才是真的，还得有一套界面让你挑。
 * 这里选了更简单的规矩：没保存就是没保存，要走的时候问你一句。
 *
 * 说句公道话，VS Code 在这件事上做得更多：它默认开着“热退出”（hot exit），关掉窗口时会把没保存的内容留着，下次打开还原给你。
 * 这里没做，是因为要做好就得把“三份版本怎么挑”那套界面也做出来。现在先用最简单也最不会让人糊涂的办法，@unclear 里记着这一点。
 */
const drafts = new Map<string, string>();

export function readDraft(id: string): string | undefined {
  return drafts.get(id);
}

export function writeDraft(id: string, text: string): void {
  drafts.set(id, text);
}

export function discardDraft(id: string): void {
  drafts.delete(id);
}
